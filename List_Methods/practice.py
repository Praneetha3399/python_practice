#  List Methods
# Append
item1 = [1,2,3]

item1.append(4)

print(item1)

# Extend
item2 = [1,2,3]
item2.extend([4,5])

print(item2)

# insert()
item3 = [1,2,3]
item3.insert(1, 8)

print(item3)

# remove()

item4 = [1,2,3]

item4.remove(3)

print(item4)

# pop()

item5 = [1,2,3]

item5.pop(2)

print(item5)

# sort()

item6 = [4,2,3,1]

item6.sort()

print(item6)

# reverse()

item7 = [1,2,3]

item7.reverse()

print(item7)